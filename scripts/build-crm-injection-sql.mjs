function sqlStr(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}

function defaultImpression(cy, cl) {
  return `${cy} — جوهرٌ من ${cl}: نقدّمها للعميل كفصلٍ متناغم ضمن رحلة واحدة، بإيقاعٍ فاخر يحترم الوقت والذوق.`;
}

function bookingSearchUrl(cityLabelAr, countryLabelAr) {
  const q = encodeURIComponent(`${cityLabelAr} ${countryLabelAr}`);
  return `https://www.booking.com/searchresults.html?ss=${q}`;
}

function buildDestinationsRows() {
  const rows = [];
  for (const co of TRIP) {
    const b = COUNTRY_BLOCK[co.id];
    if (!b) throw new Error('Missing country block ' + co.id);
    for (const city of co.cities) {
      const key = `${co.id}:${city.id}`;
      const imp = IMP[key] || defaultImpression(city.labelAr, co.labelAr);
      rows.push({
        country_id: co.id,
        city_id: city.id,
        culture: b.culture,
        guidelines: b.guidelines,
        weather_seasons: b.weather,
        professional_impression: imp,
      });
    }
  }
  return rows;
}

