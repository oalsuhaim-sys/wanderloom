export function getExpertHandbookTab(id: ExpertHandbookTabId): ExpertHandbookTab {
  return EXPERT_HANDBOOK_TABS.find((t) => t.id === id) ?? EXPERT_HANDBOOK_TABS[0]!;
}

export function parseExpertHandbookTab(
  raw: string | null | undefined,
): ExpertHandbookTabId {
  const v = String(raw ?? '').trim().toLowerCase();
  if (v === 'proposals' || v === 'itineraries' || v === 'ai' || v === 'crm') return v;
  return 'proposals';
}
