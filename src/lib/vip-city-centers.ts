/** Lower-case, strip Arabic diacritics/tatweel and unify alef / yaa / taa-marbuta forms. */
export function normalizePlaceKey(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[ً-ٰٟـ]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
}

