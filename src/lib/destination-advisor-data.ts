import { TRIP_DESTINATIONS, type TripCountryId } from '@/lib/trip-destination-data';

export type SeasonKey = 'winter' | 'spring' | 'summer' | 'autumn';

export type SeasonStatus = 'recommended' | 'not_recommended';

export type SeasonAdvisorData = {
  name: string;
  months: string[];
  /** Typical daily low – high in the reference city, e.g. "9°C – 22°C". */
  avgTemp: string;
  status: SeasonStatus;
  advice: string;
  /** A real, dated seasonal event or hidden gem. */
  hiddenEvents: string;
  activities: string[];
  images: string[];
};

export type CountryAdvisorData = {
  name: string;
  /** City the temperatures refer to (shown next to the temperature). */
  refCity?: string;
  seasons: Record<SeasonKey, SeasonAdvisorData>;
};

export const SEASON_KEYS: SeasonKey[] = ['winter', 'spring', 'summer', 'autumn'];

const unsplash = (photoId: string, w = 800) =>
  `https://images.unsplash.com/${photoId}?q=80&w=${w}&auto=format&fit=crop`;

const SEASON_NAME: Record<SeasonKey, string> = {
  winter: 'الشتاء',
  spring: 'الربيع',
  summer: 'الصيف',
  autumn: 'الخريف',
};

const NORTH_MONTHS: Record<SeasonKey, string[]> = {
  winter: ['ديسمبر', 'يناير', 'فبراير'],
  spring: ['مارس', 'أبريل', 'مايو'],
  summer: ['يونيو', 'يوليو', 'أغسطس'],
  autumn: ['سبتمبر', 'أكتوبر', 'نوفمبر'],
};

/** Southern hemisphere — seasons are reversed. */
const SOUTH_MONTHS: Record<SeasonKey, string[]> = {
  summer: ['ديسمبر', 'يناير', 'فبراير'],
  autumn: ['مارس', 'أبريل', 'مايو'],
  winter: ['يونيو', 'يوليو', 'أغسطس'],
  spring: ['سبتمبر', 'أكتوبر', 'نوفمبر'],
};

/** [low, high, recommended, advice, event, activities] */
type SeasonRow = [number, number, boolean, string, string, [string, string]];

type CountrySpec = {
  name: string;
  refCity: string;
  south?: boolean;
  /** Two free (Unsplash License) photos of the country itself. */
  images: [string, string];
  seasons: Record<SeasonKey, SeasonRow>;
};

const temp = (lo: number, hi: number) => `${lo}°C – ${hi}°C`;

function build(spec: CountrySpec): CountryAdvisorData {
  const months = spec.south ? SOUTH_MONTHS : NORTH_MONTHS;
  const images = spec.images.map((id) => unsplash(id));
  const seasons = {} as Record<SeasonKey, SeasonAdvisorData>;
  for (const key of SEASON_KEYS) {
    const [lo, hi, ok, advice, event, acts] = spec.seasons[key];
    seasons[key] = {
      name: SEASON_NAME[key],
      months: months[key],
      avgTemp: temp(lo, hi),
      status: ok ? 'recommended' : 'not_recommended',
      advice,
      hiddenEvents: event,
      activities: acts,
      images,
    };
  }
  return { name: spec.name, refCity: spec.refCity, seasons };
}

